const RCON = new Uint8Array([0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36])

const xtime = (a) => ((a << 1) ^ ((a & 0x80) ? 0x1b : 0)) & 0xff

const expandKey = (key) => {
  const w = new Uint8Array(176)
  w.set(key)
  for (let i = 16, rc = 1; i < 176; i += 4) {
    let a = w[i - 4], b = w[i - 3], c = w[i - 2], d = w[i - 1]
    if (i % 16 === 0) {
      const t = a
      a = SBOX[b] ^ RCON[rc++]
      b = SBOX[c]
      c = SBOX[d]
      d = SBOX[t]
    }
    w[i] = w[i - 16] ^ a
    w[i + 1] = w[i - 15] ^ b
    w[i + 2] = w[i - 14] ^ c
    w[i + 3] = w[i - 13] ^ d
  }
  return w
}

const encryptBlock = (state, w) => {
  const s = new Uint8Array(state)
  const addKey = (round) => {
    const o = round * 16
    for (let i = 0; i < 16; i++) s[i] ^= w[o + i]
  }
  const subShift = () => {
    s[0] = SBOX[s[0]]; s[4] = SBOX[s[4]]; s[8] = SBOX[s[8]]; s[12] = SBOX[s[12]]
    let t = SBOX[s[1]]; s[1] = SBOX[s[5]]; s[5] = SBOX[s[9]]; s[9] = SBOX[s[13]]; s[13] = t
    t = SBOX[s[2]]; s[2] = SBOX[s[10]]; s[10] = t
    t = SBOX[s[6]]; s[6] = SBOX[s[14]]; s[14] = t
    t = SBOX[s[15]]; s[15] = SBOX[s[11]]; s[11] = SBOX[s[7]]; s[7] = SBOX[s[3]]; s[3] = t
  }
  const mix = (i, a, b, c, d) => {
    const a2 = xtime(a), b2 = xtime(b), c2 = xtime(c), d2 = xtime(d)
    s[i] = a2 ^ b2 ^ b ^ c ^ d
    s[i + 1] = a ^ b2 ^ c2 ^ c ^ d
    s[i + 2] = a ^ b ^ c2 ^ d2 ^ d
    s[i + 3] = a2 ^ a ^ b ^ c ^ d2
  }
  addKey(0)
  for (let r = 1; r < 10; r++) {
    subShift()
    mix(0, s[0], s[1], s[2], s[3])
    mix(4, s[4], s[5], s[6], s[7])
    mix(8, s[8], s[9], s[10], s[11])
    mix(12, s[12], s[13], s[14], s[15])
    addKey(r)
  }
  subShift()
  addKey(10)
  state.set(s)
}

const incCounter = (counter) => {
  for (let i = 15; i >= 0; i--) {
    counter[i] = (counter[i] + 1) & 0xff
    if (counter[i]) break
  }
}

/**
 * @param {Uint8Array} key 16 字节
 * @param {Uint8Array} iv 16 字节 counter 初值
 * @param {Uint8Array} data 明文或密文
 * @returns {Uint8Array}
 */
export const aes128Ctr = (key, iv, data) => {
  if (key.length !== 16) throw new Error('AES-128 需要 16 字节密钥')
  if (iv.length !== 16) throw new Error('CTR IV 需要 16 字节')
  const roundKey = expandKey(key)
  const counter = new Uint8Array(iv)
  const block = new Uint8Array(16)
  const out = new Uint8Array(data.length)
  for (let i = 0; i < data.length; i += 16) {
    block.set(counter)
    encryptBlock(block, roundKey)
    const n = Math.min(16, data.length - i)
    for (let j = 0; j < n; j++) out[i + j] = data[i + j] ^ block[j]
    incCounter(counter)
  }
  return out
}
